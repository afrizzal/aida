// The reopen decision for a customer reply (Phase 11, D-17 and its 11-04 amendment). Both
// customer-reply paths call it inside the transaction that appends the reply:
//   - src/lib/channels/email/ingest-message.ts (an email threaded onto a ticket)
//   - src/app/api/public/status/[token]/follow-up/route.ts (the public status page)
//
// Order, always:
//   1. automatic mail returns false at once: it never reopens (D-13)
//   2. the test observer, when one is set (test seam, never set in production)
//   3. SELECT … FOR UPDATE on the one ticket row
//   4. one conditional UPDATE from RESOLVED or CLOSED to OPEN with resolvedAt null
// The returned row count decides triggeredReopen.
//
// Why the row lock comes first: a conditional UPDATE alone skips a row that fails its WHERE on
// the statement snapshot without waiting, so it would miss an agent's resolve that is still
// uncommitted. Waiting on the row lock first makes the UPDATE read the committed status. The
// auto-close job's conditional close waits on this lock too and re-checks RESOLVED afterwards,
// so a customer reply always wins: the ticket ends OPEN.
//
// Relative imports only: the worker bundles the ingest path.

/** Any transaction client that runs tagged raw SQL: prisma, scopedDb or their tx clients. */
export interface ReopenTx {
  $queryRaw<T = unknown>(query: TemplateStringsArray, ...values: unknown[]): PromiseLike<T>;
  $executeRaw(query: TemplateStringsArray, ...values: unknown[]): PromiseLike<number>;
}

export interface ReopenInput {
  orgId: string;
  ticketId: string;
  isAutoGenerated: boolean;
}

type ReopenObserver = (tx: ReopenTx, ticket: { orgId: string; ticketId: string }) => unknown;

let observer: ReopenObserver | null = null;

/**
 * Test seam only (Codex review C6): awaited with the reply's transaction client right before
 * the row lock, so a race test can record that transaction's PID. null clears it. Production
 * code never calls this.
 */
export function setReopenObserverForTests(fn: ReopenObserver | null): void {
  observer = fn;
}

/** Reopens a RESOLVED or CLOSED ticket for a customer reply. Returns whether it reopened. */
export async function reopenOnCustomerReply(
  tx: ReopenTx,
  { orgId, ticketId, isAutoGenerated }: ReopenInput,
): Promise<boolean> {
  if (isAutoGenerated) return false;
  if (observer) await observer(tx, { orgId, ticketId });

  await tx.$queryRaw`
    SELECT 1 FROM "Ticket"
    WHERE "id" = ${ticketId} AND "organizationId" = ${orgId}
    FOR UPDATE
  `;
  const changed = await tx.$executeRaw`
    UPDATE "Ticket"
    SET "status" = 'OPEN', "resolvedAt" = NULL, "updatedAt" = ${new Date()}
    WHERE "id" = ${ticketId}
      AND "organizationId" = ${orgId}
      AND "status" IN ('RESOLVED', 'CLOSED')
  `;
  return changed === 1;
}
